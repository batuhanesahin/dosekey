import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import vm from 'node:vm';
import ts from 'typescript';
const source=readFileSync(new URL('../app/page.tsx',import.meta.url),'utf8');
const helpers=source.slice(source.indexOf('const dateKey='),source.indexOf('const medicationOptions='));
const js=ts.transpile(helpers, {target:ts.ScriptTarget.ES2022});
const h=vm.runInNewContext(js+';({dateKey,addDays,elapsed,sortedDoses,nextDose})',{Date,Intl});
const p={id:1,start:'2026-09-14',interval:'Her 7 günde bir'};
const d={id:1,periodId:1,date:'2026-09-14',time:'20:00'};
assert.equal(h.nextDose(p,[d]),'2026-09-21');
assert.equal(h.nextDose({...p,interval:'Her gün'},[d]),'2026-09-15');
assert.equal(h.nextDose({...p,interval:'Her 3 günde bir'},[d]),'2026-09-17');
assert.equal(h.nextDose({...p,interval:'Plansız kullanım'},[d]),null);
assert.equal(h.nextDose(p,[]),'2026-09-14');
assert.equal(h.nextDose(p,[d,{...d,id:2,date:'2026-09-10'}]),'2026-09-21');
assert.equal(h.nextDose(p,[d,{...d,id:3,periodId:2,date:'2026-09-20'}]),'2026-09-21');
assert.equal(h.addDays('2026-12-31',1),'2027-01-01');
assert.equal(h.addDays('2028-02-28',1),'2028-02-29');
assert.equal(h.elapsed('2026-09-14','2026-09-21'),7);
assert.equal(h.sortedDoses([{...d,id:2,time:'08:00'},d])[0].id,1);
const css=readFileSync(new URL('../app/globals.css',import.meta.url),'utf8');
assert.match(css,/\.full-dialog,\.sheet-dialog\{translate:none!important/);
assert(!source.includes('const weightData='),'No synthetic chart data');
assert(source.includes('onClick={()=>goMetric("weight")}'));
console.log('14 regression checks passed: schedule, ordering, date boundaries, modal CSS, real chart data and navigation.');
